//  1-deep / 2-register FIFO синхронизатор
//  отправляющая сторона
module      wctl (
    //  сигнал валидности входных данных
    input   logic wput,
    //  указатель на место чтения, прошедший через синхронизатор
    input   logic wq2_rptr,
    //  тактирование
    input   logic wclk,
    //  сброс
    input   logic wrst_n,

    //  сигнал готовности получить новые данные
    output  logic wrdy,
    //  указатель на место записи в память
    output  logic wptr,
    //  сигнал разрешения записи в память
    output  logic we
);

//  запись осуществляется только по рукопожатию на входе
assign  we = wrdy & wput;
//  мы готовы принять
//  только при равенстве
//  когда мы записали - wptr сдвинулся
//  когда приемная сторона успешно прочитает - rptr сдвинется
//  пройдет через синхронизатор и отпр сторона
//  убедится в успешном чтении и снова будет готова принять данные
assign  wrdy = ~(wq2_rptr ^ wptr);

always @(posedge wclk or negedge wrst_n) begin
    //  сброс
    if (    !wrst_n)    wptr <= '0;
    //  XOR - это управляемый инвертор, we - сигнал о том, 
    //  что надо инвертировать
    //  по новой записи wptr инвертируется
    //  он 1 битный
    else                wptr <= wptr ^ we;
end

endmodule