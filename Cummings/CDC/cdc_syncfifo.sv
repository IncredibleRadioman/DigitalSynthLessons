//  1-deep / 2-register FIFO синхронизатор
//  вся схема целиком
module  cdc_syncfifo #(
    parameter   type dat_t = logic [7:0]
) (
    //  отправляющая сторона
    //  входные данные
    input       dat_t wdata,
    //  сигнал о их валидности
    //  типа "вставь"
    input       logic wput,
    //  тактирование отпр стороны
    input       logic wclk,
    //  сброс отпр стороны
    input       logic wrst_n,
    //  сигнал готовности отпр стороны принять новые данные
    output      logic wrdy,

    //  приемная сторона
    //  сигнал от след блока - что он готов забрать данные
    input       logic rget,
    //  тактирование приемной стороны
    input       logic rclk,
    //  сброс приемной стороны
    input       logic rrst_n,
    //  данные, отправляемые в след блок
    output      dat_t rdata,
    //  сигнал след блоку, что данные готовы для чтения
    output      logic rrdy
);

//  сигнал, указывающий на адрес записи в память
//  он туда-сюда - иы то пишем в 0, то в 1 ячейку
logic       wptr;
//  сигнал разрешения записи - по рукопожатию на входе
logic       we;
//  указатель на место чтения, пришедший в отпр сторону через синхронизатор
//  отпр сторона отслеживает равенство wptr и rptr
//  как только равны - мы готовы получить новые данные
//  проще говоря - получатель успешно принял данные при равенсте
logic       wq2_rptr;
//  указатель на место чтения
//  когда мы записали, то указатель записи сдвигается
//  и пока данные не будут синхронно прочитаны на приемной стороне
//  этот указатель будет не равен месту записи
logic       rptr;
//  указатель на место записи, пришедший в приемную сторону через
//  синхронизатор, по неравенству указателей
//  приемная сторона понимает - данные записаны в память
//  и поднимает rrdy и далее ждет прочтения сигналом rget
logic       rq2_wptr;

//  объект отпр стороны
wctl        wctl(.*);
//  объект приемной стороны
rctl        rctl(.*);

//  синхронизатор, проводящий указатель на место
//  записи в приемную сторону
sync2       w2r_sync(   .q(rq2_wptr),
                        .d(wptr),
                        .clk(rclk),
                        .rst_n(rrst_n));

//  синхронизатор, проводящий указатель на место
//  чтения в отпр сторону
sync2       r2w_sync(   .q(wq2_wptr),
                        .d(rptr),
                        .clk(wclk),
                        .rst_n(wrst_n));                       

//  непосредственно память
//  по сути - буфер между сторонами
dp_ram2 #(dat_t) dpram (    .q(rdata),
                            .d(wdata),
                            .waddr(wptr),
                            .raddr(rptr),
                            .we(we),
                            .clk(wclk));

endmodule