//  описание MCP с подтверждающей ОС целиком
module  mcp_blk #(
    parameter       type dat_t = logic[7:0]
) (
    //  валидность входных данных от передатчика
    input           logic asend,
    //  сами данные от передатчика
    input           logic [7:0] adatain,
    //  тактирование в отпр домене
    input           logic aclk,
    //  сброс в отпр домене
    input           logic arst_n,
    //  готовность отпр домена принять новые данные от передатчика
    output          logic aready,
    
    //  сигнал от получателя о загрузке
    input           logic bload,
    //  тактирование в приемном домене
    input           logic bclk,
    //  сброс в приемном домене
    input           logic brst_n,
    //  данные на выходе регистра для получателя
    output          logic [7:0] bdata,
    //  валидность данных для получателя
    output          logic bvalid
);

//  внутренняя шина данных 
//  (данные между отпр стороной и приемной)
logic       [7:0] adata;

//  ОНИ ТУДА-СЮДА! отслеживается именно их переключение, то есть
//  изменение текущего состояния
//  подтверждение от приемного домена к отпр
logic       b_ack;
//  валидность данных на отпр стороне
logic       a_en;
//  вход d генератора импульсов в приемном домене
logic       bq2_en;
//  вход d генератора импульсов в отправляющем домене
logic       aq2_ack;

//  синхронизатор в отпр домене для подтвреждающего сигнала
sync2       async ( .q(aq2_ack),
                    .d(b_ack),
                    .clk(aclk),
                    .rst_n(arst_n));

//  синхронизатор в приемном домене для сигнала об актуальности данных
sync2       bsync ( .q(bq2_en),
                    .d(a_en),
                    .clk(bclk),
                    .rst_n(brst_n));

//  схема отпр домена
//  соединить все провода с именами в компоненте с одноименными
amcp_send   alogic(.*);
//  схема приемного домена
bmcp_recv   blogic(.*);


endmodule