//  1-deep / 2-register FIFO синхронизатор
//  приемная сторона
module      rctl (
    //  сигнал от след блока
    //  о том, что он готов забрать данные
    input   logic rget,
    //  указатель на место записи из отпр стороны,
    //  прошедший через синхронизатор сюда
    input   logic rq2_wptr,
    //  тактирование
    input   logic rclk,
    //  сброс
    input   logic rrst_n,

    //  сигнал о том, что приемная сторона готова отдать данные
    output  logic rrdy,
    //  указатель на место чтения
    output  logic rptr    
);

//  текущее состояние
typedef enum {xxx, VALID} status_e;
status_e status;

//  текущее состояние определяется сигналом готовности
//  отдать данные
assign status = status_e'{rrdy};

//  если данные были готовы и получатель запросил их
//  произошло рукопожатие
//  этот сигнал разрешает инкремент указателя чтения
assign rinc = rrdy & rget;
//  мы готовы отдать данные
//  если пришедший через синхронизатор
//  указатель на адрес записи не равен указателю на адрес чтения
//  то есть данные уже положены - можно забирать
assign rrdy = (rq2_wptr ^ rptr);

always @(posedge rclk or negedge rrst_n) begin
    //  при сбросе указатель обнуляеся
    if (    !rrst_n)    rptr <= '0;
    //  по рукопожатию - инвертируем rptr
    //  XOR - это управляемый инвертор
    else                rptr <= rptr ^ rinc;

end

endmodule